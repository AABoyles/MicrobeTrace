// Records which version of each bundled library dist/ and vendor/ were built
// from (#200), so a deployed copy can be checked when an advisory lands.
//
//   node scripts/write-versions.js out.json package [package...]
//
// Versions come from the installed packages (so from package-lock.json under
// npm ci). Patched packages say so. bx-distance-models is not on NPM; its
// commit is recorded in vendor/README.md.

const fs = require('fs');
const path = require('path');

const patched = {
  tn93: 'resolutionsCount table fixed (scripts/patch-tn93.js)',
  tidytree: 'interrupted redraws no longer reject (scripts/patch-tidytree.js)'
};

const [out, ...names] = process.argv.slice(2);
if (!out || !names.length) {
  console.error('Usage: node scripts/write-versions.js out.json package [package...]');
  process.exit(1);
}

const packages = {};
for (const name of [...new Set(names)].sort()) {
  const manifest = require(path.join(__dirname, '..', 'node_modules', name, 'package.json'));
  packages[name] = { version: manifest.version, license: manifest.license || null };
  if (patched[name]) packages[name].patched = patched[name];
}

fs.writeFileSync(out, JSON.stringify({
  note: 'Generated by scripts/bundle.sh. bx-distance-models (vendor/bx_distance_models*) is not on NPM: see vendor/README.md.',
  packages
}, null, 2) + '\n');
